/**
 * Given incoming parsed messages (with contentHash already populated) and
 * the set of hashes already in the DB for this project, return only the
 * messages that are genuinely new.
 */
export function filterNewMessages(
  incoming: Array<{ contentHash?: string; id: string }>,
  existingHashes: Set<string>
): { newIndices: number[]; duplicateCount: number } {
  const newIndices: number[] = [];
  let duplicateCount = 0;
  const seenInBatch = new Set<string>();

  for (let i = 0; i < incoming.length; i++) {
    const hash = incoming[i].contentHash;
    if (!hash) {
      // No hash = can't dedup, include it
      newIndices.push(i);
      continue;
    }
    if (existingHashes.has(hash) || seenInBatch.has(hash)) {
      duplicateCount++;
    } else {
      newIndices.push(i);
      seenInBatch.add(hash);
    }
  }

  return { newIndices, duplicateCount };
}

